valid = False
while valid==False:
  s = input("첫번째 DNA 서열을 입력하시오. : ")
  t = input("두번째 DNA 서열을 입력하시오. : ")
  s=s.upper()
  t=t.upper()
  if len(s)>1000:
    print("DNA 서열 길이 제한을 초과하였습니다. DNA 서열을 다시 입력하시오.")
    continue
  if len(t)>1000:
    print("DNA 서열 길이 제한을 초과하였습니다. DNA 서열을 다시 입력하시오.")
    continue
  if len(s)!=len(t):
    print("DNA 서열 길이가 다릅니다. DNA 서열을 다시 입력하시오.")
    continue
  i=0
  count=0
  has_error=False
  while i<len(t):
    if t[i] not in ("A","G","C","T"):
      print("유효하지 않은 입력값입니다. DNA 서열을 다시 입력하시오.")
      has_error=True
      break
    if s[i]!=t[i]:
      count += 1
    i += 1
  if has_error:
    continue

  print(f"Hamming distance : {count}")
  valid = True

