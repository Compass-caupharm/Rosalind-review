valid = False
while valid==False:
  t = input("RNA로 전사할 DNA 서열을 입력하시오. : ")
  t=t.upper()
  if len(t)>1000:
    print("DNA 서열 길이 제한을 초과하였습니다. DNA 서열을 다시 입력하시오.")
    continue
  i=0
  has_error=False
  while i<len(t):
    if t[i] not in ("A","G","C","T"):
      print("유효하지 않은 입력값입니다. DNA 서열을 다시 입력하시오.")
      has_error=True
      break
    i += 1
  if has_error:
    continue

  u = t.replace("T","U")
  print(f"전사된 RNA 서열 : {u}")
  valid = True