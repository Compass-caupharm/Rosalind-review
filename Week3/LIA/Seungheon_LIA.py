import math

k = 5
n = 7

org = 2**k #k번째 Gen의 총 개체 수
p = 0.25 #어떤 유전자형을 가지더라도 잡종과 교배하면 Aa Bb를 가질 확률 모든 개체 동일! = 0.25
prob = 0
sum = 0
for i in range(n,org+1):
  comb = math.comb(org,i)
  sum += comb*(p**i)*((1 - p) ** (org - i))

print(f"{sum:.6f}")