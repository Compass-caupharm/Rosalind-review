err1=True
while err1==True:

  n = int(input("지나간 세월을 입력해주세요. (month) : "))
  m = int(input("토끼의 수명을 입력해주세요. (month) : "))

  if n>100 or m>21:
    print("숫자가 너무 커요. 다시 입력해주세요.")
    continue
  else:
    err1=False

#배열 baby는 새로 태어난 쌍 수, org는 총 쌍 수
baby = [0]*(n+1)
org = [0]*(n+1)
baby[0] = 0
org[0] = 1
#i는 지나간 개월 수
for i in range(1,n+1):
  baby[i] = org[i-1] - baby[i-1]
  if i-m>=0:
    die = baby[i-m]
  else:
    die = 0
  org[i] = org[i-1] + baby[i] - die

print(f"살아있는 토끼 쌍 수 = {org[n]}")