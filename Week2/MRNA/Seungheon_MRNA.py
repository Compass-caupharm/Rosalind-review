#딕셔너리 설정 : 각 아미노산마다 대응되는 코돈의 개수
codon = {
  'A': 4, 'R': 6, 'N': 2, 'D': 2,
  'C': 2, 'E': 2, 'Q': 2, 'G': 4,
  'H': 2, 'I': 3, 'L': 6, 'K': 2,
  'M': 1, 'F': 2, 'P': 4, 'S': 6,
  'T': 4, 'W': 1, 'Y': 2, 'V': 4
  }


#단백질 아미노산 서열 입력받기
p = input("가능한 mRNA의 개수를 계산할 아미노산 서열을 입력하시오. : ")
p=p.upper()
if len(p)>1000:
  print("단백질이 길이 제한을 초과하였습니다. 다시 입력하시오.")
  exit()
i=0
has_error=False
while i<len(p):
  if p[i] not in ("A","R","N","D","C","E","Q","G","H","I","L","K","M","F","P","S","T","W","Y","V"):
    print("유효하지 않은 입력값입니다. 아미노산 서열을 다시 입력하시오.")
    has_error=True
    break
  i += 1
  if has_error:
    continue

# mRNA 개수 계산 (종결코돈 고려)
s=1
j=0
while j<len(p):
  s*=codon[p[j]]
  j+=1
s=s*3
a=s%1000000


print(f"Total number of different RNA strings : {a}")